/** Maps the registry's string icon keys to lucide line icons, so workers never import React. */
import {
  Calculator,
  Combine,
  Crop,
  Eraser,
  EyeOff,
  FileArchive,
  FileImage,
  FilePen,
  FileUser,
  FileOutput,
  IdCard,
  LayoutDashboard,
  LayoutGrid,
  LockKeyhole,
  Maximize2,
  Palette,
  QrCode,
  ReceiptText,
  Repeat2,
  Scaling,
  ScanText,
  Shrink,
  Signature,
  Split,
  Stamp,
  Type,
  type LucideIcon,
} from "lucide-react";
import type { IconKey } from "@/tools/types";

const icons: Record<IconKey, LucideIcon> = {
  compress: Shrink,
  resize: Scaling,
  crop: Crop,
  convert: Repeat2,
  cutout: Eraser,
  id: IdCard,
  watermark: Type,
  upscale: Maximize2,
  palette: Palette,
  collage: LayoutDashboard,
  merge: Combine,
  split: Split,
  "compress-pdf": FileArchive,
  "pdf-to-image": FileImage,
  "image-to-pdf": FileOutput,
  stamp: Stamp,
  sign: Signature,
  lock: LockKeyhole,
  organize: LayoutGrid,
  ocr: ScanText,
  markdown: FilePen,
  resume: FileUser,
  invoice: ReceiptText,
  qr: QrCode,
  payroll: Calculator,
  metadata: EyeOff,
};

export function ToolIcon({ name, className }: { name: IconKey; className?: string }) {
  const Icon = icons[name];
  return <Icon aria-hidden className={className ?? "size-4"} strokeWidth={1.75} />;
}
